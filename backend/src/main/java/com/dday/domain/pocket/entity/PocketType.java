package com.dday.domain.pocket.entity;

/**
 * 포켓의 용도. 사용자마다 이 네 개가 고정으로 하나씩 생긴다.
 *
 * <p>포켓은 자금을 직접 보관하지 않는다. 이용자 계좌 위에 얹는 <b>목적별 관리 계층</b>이다.
 * 그래서 여기 있는 건 "어떤 목적의 돈인가"를 가르는 분류이지 계좌가 아니다.
 *
 * <p>화면에 띄울 이름은 여기 두지 않고 {@link Pocket#getPocketName()}에 행 단위로 둔다 —
 * 사용자가 포켓 이름을 바꿀 수 있어야 하는데, enum에 박아두면 전원이 같은 이름을 쓰게 된다.
 *
 * <p>선언 순서가 곧 화면에 뿌리는 순서다. 필수 지출이 가장 먼저 확보돼야 할 돈이라
 * {@link #ESSENTIAL}이 앞에 온다. {@code EnumType.STRING}으로 저장하므로 DB 정렬은
 * 알파벳순이 되어버린다 — 정렬은 이 선언 순서로 서비스에서 다시 잡는다.
 */
public enum PocketType {

    /** 필수 — 주거·공과금·통신처럼 안 쓸 수 없는 지출 */
    ESSENTIAL,

    /** 자유 — 식비·쇼핑·여가처럼 조절 가능한 지출 */
    FREE,

    /** 비상금 — 예기치 못한 상황에 대비해 따로 확보하는 자금 */
    EMERGENCY,

    /** 미래자산 — 투자·적립으로 쌓아가는 장기 목표 */
    FUTURE_ASSET
}
